def make_user(spending_limit=None, threshold=80, spending_period=BudgetPeriod.MONTHLY):
    user = MagicMock(spec=User)
    user.user_id = uuid.uuid4()
    user.spending_limit = spending_limit
    user.threshold = threshold
    user.spending_period = spending_period
    return user

def make_category(category_id=None, name="Test Category", parent_id=None):
    cat = MagicMock(spec=Category)
    cat.category_id = category_id or uuid.uuid4()
    cat.name = name
    cat.parent_id = parent_id
    cat.is_active = True
    cat.display_order = 1
    return cat

def make_budget(is_bill=False, status=BillStatus.PENDING):
    budget = MagicMock(spec=Budget)
    budget.budget_id = uuid.uuid4()
    budget.category_id = uuid.uuid4()
    budget.is_bill = is_bill
    budget.bill_name = "Test Bill" if is_bill else None
    budget.bill_status = status
    budget.due_date = datetime.now(timezone.utc) + timedelta(days=5)
    budget.last_paid_at = None
    return budget

def mock_refresh(obj):
    """Simulate SQLAlchemy refresh() populating autogenerated fields."""
    obj.budget_id = uuid.uuid4()
    obj.created_at = datetime.now(timezone.utc)

