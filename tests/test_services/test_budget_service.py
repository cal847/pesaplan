class TestCreateBudget:
    def test_create_budget_success(self):
        """Validates that a budget is successfully created when category exists and no overlap occurs."""
        db = MagicMock()
        service = BudgetService(db)
        user_id = uuid.uuid4()
        cat_id = uuid.uuid4()
        
        db.query.return_value.filter.return_value.first.side_effect = [
            make_category(cat_id), None
        ]
        db.add = MagicMock()
        db.commit = MagicMock()
        db.refresh.side_effect = mock_refresh
        
        start = datetime.now(timezone.utc)
        # Schema requires end_date, so we must provide a valid one
        data = BudgetCreate(
            category_id=cat_id, 
            amount=Decimal("100.00"), 
            period=BudgetPeriod.MONTHLY,
            start_date=start, 
            end_date=start + timedelta(days=30), 
            is_bill=False
        )
        
        result = service.create_budget(user_id, data)
        
        assert result.amount == Decimal("100.00")
        db.add.assert_called_once()
        db.commit.assert_called_once()

    def test_create_budget_category_not_found(self):
        """Ensures CategoryNotFoundException is raised when the specified category doesn't exist."""
        db = MagicMock()
        service = BudgetService(db)
        db.query.return_value.filter.return_value.first.return_value = None
        
        start = datetime.now(timezone.utc)
        data = BudgetCreate(
            category_id=uuid.uuid4(), amount=Decimal("100.00"), period=BudgetPeriod.MONTHLY,
            start_date=start, end_date=start + timedelta(days=30), is_bill=False
        )
        
        with pytest.raises(CategoryNotFoundException):
            service.create_budget(uuid.uuid4(), data)

    def test_create_budget_overlap_raises_error(self):
        """Verifies that BudgetAlreadyExistsException is raised when an overlapping budget exists."""
        db = MagicMock()
        service = BudgetService(db)
        cat_id = uuid.uuid4()
        
        db.query.return_value.filter.return_value.first.side_effect = [
            make_category(cat_id), make_budget()
        ]
        
        start = datetime.now(timezone.utc)
        data = BudgetCreate(
            category_id=cat_id, amount=Decimal("100.00"), period=BudgetPeriod.MONTHLY,
            start_date=start, end_date=start + timedelta(days=30), is_bill=False
        )
        
        with pytest.raises(BudgetAlreadyExistsException):
            service.create_budget(uuid.uuid4(), data)

    def test_create_budget_with_december_start_date(self):
        """Tests that a budget starting in December is successfully created with a valid end date."""
        db = MagicMock()
        service = BudgetService(db)
        cat_id = uuid.uuid4()
        
        db.query.return_value.filter.return_value.first.side_effect = [make_category(cat_id), None]
        db.add = MagicMock()
        db.commit = MagicMock()
        db.refresh.side_effect = mock_refresh
        
        start = datetime(2026, 12, 15, tzinfo=timezone.utc)
        # Schema requires end_date, so we provide the calculated rollover date
        end = datetime(2027, 1, 31, 23, 59, 59, 999999, tzinfo=timezone.utc)
        data = BudgetCreate(
            category_id=cat_id, amount=Decimal("100.00"), period=BudgetPeriod.MONTHLY,
            start_date=start, end_date=end, is_bill=False
        )
        
        result = service.create_budget(uuid.uuid4(), data)
        
        assert result.end_date.month == 1
        assert result.end_date.year == 2027


