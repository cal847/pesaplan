class TestCalculateBudgetProgress:
    def _run(self, spent, spending_limit, threshold=80):
        db = MagicMock()
        user = make_user(spending_limit=spending_limit, threshold=threshold)
        service = BudgetService(db)

        with patch("app.services.budget_service.get_user_by_id", return_value=user), \
             patch("app.services.budget_service.get_period_dates", return_value=(
                 datetime(2026, 3, 1, tzinfo=timezone.utc),
                 datetime(2026, 3, 31, tzinfo=timezone.utc),
             )), \
             patch.object(service, "_calculate_total_period_spending", return_value=Decimal(str(spent))):
            return service.calculate_budget_progress(user.user_id, BudgetPeriod.MONTHLY)

    def test_on_track(self):
        """Confirms status is 'on_track' when spending is well below the threshold."""
        result = self._run(spent=2000, spending_limit=Decimal("10000.00"))
        assert result.status == "on_track"
        assert result.remaining == Decimal("8000.00")

    def test_exactly_at_threshold(self):
        """Validates that spending exactly at the threshold (80%) triggers 'warning' status."""
        result = self._run(spent=8000, spending_limit=Decimal("10000.00"), threshold=80)
        assert result.status == "warning"

    def test_exceeded_caps_remaining_at_zero(self):
        """Ensures remaining amount never goes negative, capping at 0.00 when budget is exceeded."""
        result = self._run(spent=15000, spending_limit=Decimal("10000.00"))
        assert result.status == "exceeded"
        assert result.remaining == Decimal("0.00")

    def test_zero_spending_limit_avoids_division_by_zero(self):
        """Prevents ZeroDivisionError when spending limit is set to 0.00."""
        result = self._run(spent=5000, spending_limit=Decimal("0.00"))
        assert result.status == "on_track"
        assert result.percentage == 0.0

    def test_none_spending_limit_defaults_to_zero(self):
        """Handles the case where spending_limit is None by defaulting to 0.00."""
        result = self._run(spent=5000, spending_limit=None)
        assert result.status == "on_track"
        assert result.spending_limit == Decimal("0.00")


